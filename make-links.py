#!/usr/bin/env python3
"""Write an invisible TikZ link box over each node of a dot graph that has a URL.
pdflatex drops the links of an included PDF, so prereq-chart.tex lays these on top.

Usage: make-links.py graph.json graph.pdf links.tex
  graph.json, graph.pdf: dot -Tjson and dot -Tpdf of the same .gv file
"""
import json
import re
import subprocess
import sys

json_path, pdf_path, out_path = sys.argv[1:4]
g = json.load(open(json_path))
x0, y0, x1, y1 = (float(v) for v in g["bb"].split(","))
info = subprocess.run(["pdfinfo", pdf_path], capture_output=True, text=True, check=True).stdout
pw, ph = (float(v) for v in re.search(r"Page size:\s+([\d.]+) x ([\d.]+)", info).groups())
# dot centres the drawing on the page: graph coords -> page coords
dx = (pw - (x1 - x0)) / 2 - x0
dy = (ph - (y1 - y0)) / 2 - y0

links = []
for o in g.get("objects", []):
    if "URL" not in o or "pos" not in o:
        continue
    cx, cy = (float(v) for v in o["pos"].split(","))
    w, h = float(o["width"]) * 72, float(o["height"]) * 72
    url = o["URL"].replace("%", "\\%").replace("#", "\\#")
    links.append(
        f"\\node[inner sep=0pt] at ({cx + dx:.2f}bp,{cy + dy:.2f}bp) "
        f"{{\\href{{{url}}}{{\\phantom{{\\rule{{{w:.2f}bp}}{{{h:.2f}bp}}}}}}}};")
open(out_path, "w").write("% generated by make-links.py; do not edit\n" + "\n".join(links) + "\n")
print(f"{len(links)} links -> {out_path}")
