#!/usr/bin/env python3
"""Find a blank spot for the legend, so it never covers a box or an arrow.

Usage: place-legend.py graph.pdf legend.pdf legend-pos.tex

Rasterizes both PDFs at 1 pixel per bp. Tries the bottom-left corner, then the
left edge from the top down (just under the title). Writes \\legendx, \\legendy:
the legend's offset from the graph's lower-left corner. If nothing is clear,
warns and uses the corner.
"""
import subprocess
import sys

PAD = 12        # bp of blank space required around the legend's ink
PAD_ABOVE = 36  # more above, so the legend does not crowd the title
WHITE = 250     # gray level counted as blank (0 black, 255 white)
STEP = 2        # bp per step when scanning

graph_pdf, legend_pdf, out_path = sys.argv[1:4]


def raster(pdf):
    data = subprocess.run(["pdftoppm", "-r", "72", "-gray", "-singlefile", pdf],
                          capture_output=True, check=True).stdout
    magic, w, h, maxval, pixels = data.split(maxsplit=4)
    assert magic == b"P5" and maxval == b"255"
    w, h = int(w), int(h)
    return w, h, [pixels[r * w:(r + 1) * w] for r in range(h)]


gw, gh, grows = raster(graph_pdf)
lw, lh, lrows = raster(legend_pdf)

# bounding box of the legend's ink, in its own pixels (rows from the top)
ink_rows = [r for r in range(lh) if min(lrows[r]) < WHITE]
ink_cols = [c for c in range(lw) if any(lrows[r][c] < WHITE for r in ink_rows)]
lx0, lx1, ly0, ly1 = min(ink_cols), max(ink_cols), min(ink_rows), max(ink_rows)


def clear(x, y):
    """Is the graph blank under the legend's ink plus padding, with the legend's
    lower-left corner at (x, y) bp from the graph's lower-left corner?"""
    top = gh - (y + lh)  # graph row of the legend's top edge
    c0, c1 = max(0, x + lx0 - PAD), min(gw, x + lx1 + PAD + 1)
    r0, r1 = max(0, top + ly0 - PAD_ABOVE), min(gh, top + ly1 + PAD + 1)
    if c0 >= c1 or r0 >= r1:
        return False
    return all(min(grows[r][c0:c1]) >= WHITE for r in range(r0, r1))


x = 0
y = next((y for y in [0, *range(gh - lh, -1, -STEP)] if clear(x, y)), None)
if y is None:
    y = 0
    print("place-legend.py: WARNING: no clear spot on the left; the legend covers part of the graph",
          file=sys.stderr)

with open(out_path, "w") as f:
    f.write("% generated by place-legend.py; do not edit\n")
    f.write(f"\\newcommand{{\\legendx}}{{{x}bp}}\n\\newcommand{{\\legendy}}{{{y}bp}}\n")
print(f"legend -> ({x},{y}) bp")
